"""Regenerate BearSSL trust anchors from the checked-in Mozilla/curl CA bundle.
Requires cryptography. No network access; review bundle updates separately.
"""
from pathlib import Path
import hashlib
from cryptography import x509
from cryptography.hazmat.primitives.asymmetric import rsa, ec
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

root = Path(__file__).resolve().parent.parent
bundle = root / 'third_party/bearssl/cacert.pem'
data = bundle.read_bytes()
lines = ['// Generated by tools/build-trust-anchors.py; Mozilla CA bundle via curl.se.',
         '// Bundle SHA256: ' + hashlib.sha256(data).hexdigest()]
entries = []
def array(name, value):
    lines.append('static unsigned char %s[] = {%s};' % (name, ','.join('0x%02x' % b for b in value)))
for i, cert in enumerate(x509.load_pem_x509_certificates(data)):
    name = 'ca%d' % i
    array(name + '_dn', cert.subject.public_bytes())
    key = cert.public_key()
    if isinstance(key, rsa.RSAPublicKey):
        numbers = key.public_numbers()
        array(name + '_n', numbers.n.to_bytes((numbers.n.bit_length()+7)//8, 'big'))
        array(name + '_e', numbers.e.to_bytes((numbers.e.bit_length()+7)//8, 'big'))
        entries.append('{{%s_dn,sizeof(%s_dn)},BR_X509_TA_CA,{BR_KEYTYPE_RSA,{{%s_n,sizeof(%s_n),%s_e,sizeof(%s_e)}}}}' % (name, name, name, name, name, name))
    elif isinstance(key, ec.EllipticCurvePublicKey):
        curve = {'secp256r1': 23, 'secp384r1': 24, 'secp521r1': 25}[key.curve.name]
        array(name + '_q', key.public_bytes(Encoding.X962, PublicFormat.UncompressedPoint))
        # Initialize union as RSA; set EC fields once before opening TLS.
        entries.append('{{%s_dn,sizeof(%s_dn)},BR_X509_TA_CA,{BR_KEYTYPE_EC,{{0,0,0,0}}}}' % (name, name))
        lines.append('// EC %d %d %s_q' % (i, curve, name))
    else:
        raise ValueError('Unsupported CA key type')
lines.append('static br_x509_trust_anchor gx_trust[] = {\n' + ',\n'.join(entries) + '\n};')
lines.append('static void gx_init_trust(){')
for i, cert in enumerate(x509.load_pem_x509_certificates(data)):
    key = cert.public_key()
    if isinstance(key, ec.EllipticCurvePublicKey):
        curve = {'secp256r1': 23, 'secp384r1': 24, 'secp521r1': 25}[key.curve.name]
        lines.append('gx_trust[%d].pkey.key.ec.curve=%d;gx_trust[%d].pkey.key.ec.q=ca%d_q;gx_trust[%d].pkey.key.ec.qlen=sizeof(ca%d_q);' % (i, curve, i, i, i, i))
lines.append('}')
(root / 'src/trust_anchors.h').write_text('\n'.join(lines) + '\n', encoding='ascii')
print('Generated', len(entries), 'trust anchors')
