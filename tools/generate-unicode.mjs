// Regenerate the compact Unicode categories used by native BPE pre-tokenization.
import { writeFileSync } from 'node:fs';
const ranges = [];
let start = 0, previous = 0;
for (let cp = 0; cp <= 0x110000; ++cp) {
  const s = cp < 0x110000 ? String.fromCodePoint(cp) : '';
  // Python/Unicode regex \s includes these C0 separators as well.
  const kind = /\p{L}/u.test(s) ? 1 : /\p{N}/u.test(s) ? 2
    : /\p{White_Space}/u.test(s) || (cp >= 0x1c && cp <= 0x1f) ? 3 : 0;
  if (kind !== previous) {
    if (previous) ranges.push(`  {0x${start.toString(16)},0x${(cp-1).toString(16)},${previous}}`);
    start = cp; previous = kind;
  }
}
writeFileSync(new URL('../src/unicode_ranges.h', import.meta.url),
  '// Generated by tools/generate-unicode.mjs using Node Unicode '+process.versions.unicode+'.\n' +
  'struct gx_unicode_range { u32 lo, hi; int kind; };\n' +
  'static const gx_unicode_range gx_unicode_ranges[] = {\n'+ranges.join(',\n')+'\n};\n');
