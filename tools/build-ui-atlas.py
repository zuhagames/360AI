"""Build the embedded native UI atlas. Requires Pillow; no runtime dependencies."""
from pathlib import Path
import re
from PIL import Image

root = Path(__file__).resolve().parents[1]
atlas = Image.new('RGBA', (256, 512))
rows = re.findall(r'0x([0-9a-fA-F]{4})', (root / 'src/font16.h').read_text())
assert len(rows) == 95 * 24
for glyph in range(95):
    for y in range(24):
        bits = int(rows[glyph * 24 + y], 16)
        for x in range(16):
            if bits & (0x8000 >> x):
                atlas.putpixel(((glyph % 16) * 16 + x, (glyph // 16) * 32 + y + 4), (255, 255, 255, 255))
names = ['A', 'B', 'X', 'Y', 'LB', 'RB', 'Start', 'Back', 'Dpad', 'Right_Stick_Click', 'Left_Stick']
for i, name in enumerate(names):
    icon = Image.open(root / f'assets/input/360_{name}.png').convert('RGBA').resize((48, 48), Image.Resampling.LANCZOS)
    atlas.paste(icon, ((i % 4) * 64 + 8, 224 + (i // 4) * 64 + 8))
atlas.putpixel((255, 511), (255, 255, 255, 255))
pixels = [(a << 24) | (r << 16) | (g << 8) | b for r, g, b, a in atlas.getdata()]
runs = []
for color in pixels:
    if runs and runs[-1][1] == color:
        runs[-1][0] += 1
    else:
        runs.append([1, color])
text = '// Generated by tools/build-ui-atlas.py. Xelu CC0 prompts; see assets/input/XELU-LICENSE.txt.\n'
text += '#ifndef GX_UI_ATLAS_H\n#define GX_UI_ATLAS_H\nstatic const unsigned int gx_ui_rle[][2] = {\n'
text += ''.join(f'{{{count},0x{color:08x}u}},\n' for count, color in runs)
text += '};\n#endif\n'
(root / 'src/ui_atlas.h').write_text(text, encoding='ascii')
(root / 'build/assets').mkdir(parents=True, exist_ok=True)
atlas.save(root / 'build/assets/ui-atlas.png')
print(f'Atlas 256x512, {len(runs) * 8} embedded bytes, 512 KiB GPU texture')
